#!/usr/bin/env python3
"""
Example script showing different ways to save agent responses to markdown files
"""

from datetime import datetime
import os
from pathlib import Path
import sys

# Add current directory to path for imports
current_dir = Path(__file__).parent
sys.path.insert(0, str(current_dir))

from dotenv import load_dotenv
from multisource_news_agent import create_enhanced_news_agent
from news_reporter import NewsReporter

# Load environment variables
load_dotenv()


def method_1_direct_save():
    """Method 1: Direct capture and save"""
    print("📝 Method 1: Direct Capture and Save")

    agent = create_enhanced_news_agent()

    # Get response without printing to console
    query = "What are today's top tech news stories?"
    response = agent.run(query)

    # Create filename with timestamp
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"reports/tech_news_{timestamp}.md"

    # Create markdown content
    markdown_content = f"""# Tech News Report

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
**Query:** {query}

---

{response.content}

---
*Generated by Agno Multi-Source News Agent*
"""

    # Save to file
    os.makedirs("reports", exist_ok=True)
    with open(filename, "w", encoding="utf-8") as f:
        f.write(markdown_content)

    print(f"✅ Report saved to: {filename}")
    return filename


def method_2_using_reporter():
    """Method 2: Using the NewsReporter class"""
    print("📝 Method 2: Using NewsReporter Class")

    reporter = NewsReporter()
    agent = create_enhanced_news_agent()

    # Generate single report
    filepath = reporter.generate_report(
        agent=agent,
        query="Give me the latest AI and cryptocurrency news",
        filename="ai_crypto_news",
        title="AI & Cryptocurrency News Update",
    )

    print(f"✅ Report saved to: {filepath}")
    return filepath


def method_3_batch_reports():
    """Method 3: Generate multiple reports at once"""
    print("📝 Method 3: Batch Report Generation")

    reporter = NewsReporter()
    agent = create_enhanced_news_agent()

    queries = [
        "What are the major global news headlines today?",
        "Show me trending technology and startup news",
        "Give me financial market updates and analysis",
    ]

    filepaths = reporter.generate_multiple_reports(
        agent=agent, queries=queries, base_filename="daily_briefing"
    )

    print(f"✅ Generated {len(filepaths)} reports:")
    for filepath in filepaths:
        print(f"   - {filepath}")

    return filepaths


def method_4_daily_digest():
    """Method 4: Comprehensive daily digest"""
    print("📝 Method 4: Comprehensive Daily Digest")

    reporter = NewsReporter()
    agent = create_enhanced_news_agent()

    filepath = reporter.generate_daily_digest(agent)
    print(f"✅ Daily digest saved to: {filepath}")
    return filepath


def method_5_custom_formatting():
    """Method 5: Custom markdown formatting"""
    print("📝 Method 5: Custom Formatting")

    agent = create_enhanced_news_agent()

    # Multiple queries for different sections
    sections = [
        ("Breaking News", "What are today's most important breaking news stories?"),
        ("Tech Updates", "Give me the latest technology developments and AI news"),
        ("Market Watch", "What are the key financial market movements today?"),
    ]

    # Generate content for each section
    report_content = f"""# Comprehensive News Report

**Date:** {datetime.now().strftime("%B %d, %Y")}
**Time:** {datetime.now().strftime("%H:%M:%S")}

---

"""

    for section_title, query in sections:
        print(f"   Generating: {section_title}")
        response = agent.run(query)

        report_content += f"""## {section_title}

{response.content}

---

"""

    # Add footer
    report_content += """
## Summary

This report was generated using the Agno Multi-Source News Agent, combining information from multiple reliable news sources including HackerNews, DuckDuckGo, Reddit, Tavily, and other specialized tools.

**Sources Used:**
- HackerNews (Tech/Startup news)
- DuckDuckGo (General news search)
- Reddit (Community discussions)
- Tavily (AI-enhanced analysis)
- YFinance (Financial data)
- ArXiv (Academic research)

*Generated automatically by Agno Framework*
"""

    # Save custom formatted report
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"reports/comprehensive_report_{timestamp}.md"

    os.makedirs("reports", exist_ok=True)
    with open(filename, "w", encoding="utf-8") as f:
        f.write(report_content)

    print(f"✅ Comprehensive report saved to: {filename}")
    return filename


def main():
    """Demonstrate all methods"""
    if not os.getenv("ANTHROPIC_API_KEY"):
        print("❌ ANTHROPIC_API_KEY is required!")
        return

    print("🚀 News Report Generation Examples")
    print("=" * 50)

    try:
        # Run all examples
        method_1_direct_save()
        print()

        method_2_using_reporter()
        print()

        method_3_batch_reports()
        print()

        method_4_daily_digest()
        print()

        method_5_custom_formatting()
        print()

        print("🎉 All report generation examples completed!")
        print("📁 Check the 'reports/' folder for generated files")

        # List generated files
        reports_dir = Path("reports")
        if reports_dir.exists():
            files = list(reports_dir.glob("*.md"))
            print(f"\n📋 Generated {len(files)} report files:")
            for file in sorted(files):
                print(f"   - {file.name}")

    except Exception as e:
        print(f"❌ Error: {e}")


if __name__ == "__main__":
    main()
