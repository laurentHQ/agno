"""
Utility functions for saving agent responses to markdown reports
"""

from datetime import datetime
from pathlib import Path


def save_agent_response_to_md(
    agent, query, filename=None, title=None, reports_dir="reports", response_content=None
):
    """
    Simple function to get agent response and save it as markdown

    Args:
        agent: The Agno agent instance
        query: The query string to send to the agent
        filename: Optional filename (will auto-generate if not provided)
        title: Optional title for the report
        reports_dir: Directory to save reports (default: "reports")
        response_content: Optional pre-existing response content (skips agent query if provided)

    Returns:
        Path to the saved file
    """
    # Create reports directory if it doesn't exist
    reports_path = Path(reports_dir)
    reports_path.mkdir(exist_ok=True)

    # Generate filename if not provided
    if filename is None:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_query = "".join(c for c in query[:30] if c.isalnum() or c in (" ", "-", "_")).rstrip()
        safe_query = safe_query.replace(" ", "_")
        filename = f"news_report_{safe_query}_{timestamp}.md"

    # Ensure .md extension
    if not filename.endswith(".md"):
        filename += ".md"

    # Get response from agent or use provided content
    if response_content is None:
        print(f"🔍 Querying agent: {query}")
        response = agent.run(query)
        content = response.content
    else:
        content = response_content

    # Create markdown content
    markdown_content = f"""# {title or "News Report"}

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
**Query:** {query}

---

{content}

---
*Generated by Agno Multi-Source News Agent*
"""

    # Save to file
    filepath = reports_path / filename
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(markdown_content)

    print(f"📄 Report saved to: {filepath}")
    return filepath


def quick_news_report(query, agent_type="enhanced", filename=None):
    """
    Quick function to generate a news report with minimal setup

    Args:
        query: The news query
        agent_type: "basic" or "enhanced" (default: "enhanced")
        filename: Optional filename

    Returns:
        Path to the saved report
    """
    from pathlib import Path
    import sys

    # Add current directory to path for imports
    current_dir = Path(__file__).parent
    news_root = current_dir.parent
    sys.path.insert(0, str(news_root))
    sys.path.insert(0, str(news_root / "agents"))

    from dotenv import load_dotenv

    load_dotenv()

    if agent_type == "basic":
        from multisource_news_agent import create_basic_news_agent

        agent = create_basic_news_agent()
    else:
        from multisource_news_agent import create_enhanced_news_agent

        agent = create_enhanced_news_agent()

    return save_agent_response_to_md(agent, query, filename)


def batch_news_reports(queries, agent_type="enhanced", base_filename=None):
    """
    Generate multiple reports from a list of queries

    Args:
        queries: List of query strings
        agent_type: "basic" or "enhanced" (default: "enhanced")
        base_filename: Base name for files (will append numbers)

    Returns:
        List of paths to saved reports
    """
    from pathlib import Path
    import sys

    # Add current directory to path for imports
    current_dir = Path(__file__).parent
    news_root = current_dir.parent
    sys.path.insert(0, str(news_root))
    sys.path.insert(0, str(news_root / "agents"))

    from dotenv import load_dotenv

    load_dotenv()

    if agent_type == "basic":
        from multisource_news_agent import create_basic_news_agent

        agent = create_basic_news_agent()
    else:
        from multisource_news_agent import create_enhanced_news_agent

        agent = create_enhanced_news_agent()

    reports = []
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    for i, query in enumerate(queries, 1):
        if base_filename:
            filename = f"{base_filename}_{i:02d}_{timestamp}.md"
        else:
            filename = None

        title = f"Report {i}: {query[:50]}..."
        filepath = save_agent_response_to_md(agent, query, filename, title)
        reports.append(filepath)

    return reports


# Example usage functions
def demo_usage():
    """Demonstrate how to use the utility functions"""

    # Example 1: Simple single report
    print("Example 1: Single Report")
    quick_news_report("What are today's top tech stories?")

    # Example 2: Multiple reports
    print("\nExample 2: Multiple Reports")
    queries = ["Latest AI developments", "Cryptocurrency market updates", "Startup funding news"]
    filepaths = batch_news_reports(queries, base_filename="daily_brief")

    print(f"\nGenerated {len(filepaths)} reports:")
    for path in filepaths:
        print(f"  - {path}")


if __name__ == "__main__":
    demo_usage()
