#!/usr/bin/env python3
"""
News Reporter - Captures agent responses and saves to markdown reports
"""

from datetime import datetime
from io import StringIO
import os
from pathlib import Path
import sys

# Add current directory to path for imports
current_dir = Path(__file__).parent.parent  # Go up to /src/
project_root = current_dir.parent  # Go up to project root
sys.path.insert(0, str(project_root))
sys.path.insert(0, str(current_dir))

from dotenv import load_dotenv

from src.agents.multisource_news_agent import (
    create_basic_news_agent,
    create_enhanced_news_agent,
)

# Load environment variables
load_dotenv()


class NewsReporter:
    """Utility class to capture agent responses and save as markdown reports"""

    def __init__(self, reports_dir="reports"):
        self.reports_dir = Path(reports_dir)
        self.reports_dir.mkdir(exist_ok=True)

    def capture_response(self, agent, query, stream=True):
        """Capture agent response as string instead of printing"""
        # Create a string buffer to capture output
        output_buffer = StringIO()

        # Capture the response without streaming to console
        if stream:
            # For streaming, we need to collect chunks
            response = agent.run(query)
            return response.content
        response = agent.run(query)
        return response.content

    def save_report(self, content, filename=None, title=None, query=None):
        """Save content as markdown report with metadata"""
        if filename is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            filename = f"news_report_{timestamp}.md"

        # Ensure .md extension
        if not filename.endswith(".md"):
            filename += ".md"

        filepath = self.reports_dir / filename

        # Create markdown content with metadata
        markdown_content = self._format_markdown(content, title, query)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(markdown_content)

        return filepath

    def _format_markdown(self, content, title=None, query=None):
        """Format content as markdown with metadata header"""
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        markdown = f"""# {title or "News Report"}

**Generated:** {timestamp}
"""

        if query:
            markdown += f"**Query:** {query}\n"

        markdown += f"""
---

{content}

---
*Report generated by Agno Multi-Source News Agent*
"""
        return markdown

    def generate_report(self, agent, query, filename=None, title=None):
        """Generate a complete report from agent query"""
        print(f"🔍 Generating report for: {query}")

        # Capture the response
        content = self.capture_response(agent, query, stream=False)

        # Save to markdown
        filepath = self.save_report(content, filename, title, query)

        print(f"📄 Report saved to: {filepath}")
        return filepath

    def generate_multiple_reports(self, agent, queries, base_filename=None):
        """Generate multiple reports from a list of queries"""
        reports = []
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

        for i, query in enumerate(queries, 1):
            if base_filename:
                filename = f"{base_filename}_{i:02d}_{timestamp}.md"
            else:
                filename = f"report_{i:02d}_{timestamp}.md"

            filepath = self.generate_report(agent, query, filename, f"Report {i}")
            reports.append(filepath)

        return reports

    def generate_daily_digest(self, agent=None):
        """Generate a comprehensive daily news digest"""
        if agent is None:
            agent = create_enhanced_news_agent()

        timestamp = datetime.now().strftime("%Y%m%d")
        filename = f"daily_digest_{timestamp}.md"

        queries = [
            "What are today's top breaking news stories?",
            "Give me the latest technology and AI developments",
            "What are the major market movements and financial news?",
            "What's trending in the startup and business world?",
            "Show me important global news and developments",
        ]

        print("📰 Generating Daily News Digest...")

        all_content = []
        for i, query in enumerate(queries, 1):
            print(f"   {i}/5: {query}")
            content = self.capture_response(agent, query)
            all_content.append(f"## Section {i}: {query}\n\n{content}\n")

        # Combine all sections
        full_content = "\n".join(all_content)

        # Save comprehensive report
        filepath = self.save_report(
            full_content, filename, f"Daily News Digest - {datetime.now().strftime('%B %d, %Y')}"
        )

        print(f"📊 Daily digest saved to: {filepath}")
        return filepath


def main():
    """Main function with examples"""
    # Check API key
    if not os.getenv("ANTHROPIC_API_KEY"):
        print("❌ ANTHROPIC_API_KEY is required!")
        return

    # Create reporter
    reporter = NewsReporter()

    # Create agents
    print("🔧 Creating news agents...")
    basic_agent = create_basic_news_agent()
    enhanced_agent = create_enhanced_news_agent()

    print("\n🎯 Choose report type:")
    print("1. Single Query Report")
    print("2. Multiple Query Reports")
    print("3. Daily News Digest")
    print("4. Tech News Focus")
    print("5. Financial News Focus")

    try:
        choice = input("\nEnter your choice (1-5): ").strip()

        if choice == "1":
            query = input("Enter your news query: ").strip()
            if query:
                reporter.generate_report(enhanced_agent, query)

        elif choice == "2":
            queries = []
            print("Enter multiple queries (empty line to finish):")
            while True:
                query = input("Query: ").strip()
                if not query:
                    break
                queries.append(query)

            if queries:
                reporter.generate_multiple_reports(enhanced_agent, queries)

        elif choice == "3":
            reporter.generate_daily_digest(enhanced_agent)

        elif choice == "4":
            tech_queries = [
                "What are the latest AI and machine learning breakthroughs?",
                "Show me trending startup news and funding announcements",
                "What's happening in the developer and open source community?",
                "Give me the latest tech industry news and analysis",
            ]
            reporter.generate_multiple_reports(enhanced_agent, tech_queries, "tech_news")

        elif choice == "5":
            finance_queries = [
                "What are today's major market movements and trends?",
                "Give me cryptocurrency and blockchain news updates",
                "Show me important economic indicators and financial news",
                "What are the latest investment and trading developments?",
            ]
            reporter.generate_multiple_reports(enhanced_agent, finance_queries, "finance_news")

        else:
            print("Invalid choice.")

    except KeyboardInterrupt:
        print("\n👋 Report generation cancelled.")
    except Exception as e:
        print(f"❌ Error: {e}")


if __name__ == "__main__":
    main()
