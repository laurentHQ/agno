def main():
    """Interactive Tech News Hub"""
    if not os.getenv("ANTHROPIC_API_KEY"):
        print("❌ ANTHROPIC_API_KEY is required!")
        return

    print("🌟 Tech News Hub - GitHub Trending + News Integration")
    print("=" * 60)

    hub = TechNewsHub()

    print("🎯 Choose report type:")
    print("1. Comprehensive Tech Report (News + GitHub Trending)")
    print("2. Language Ecosystem Report (specific programming language)")
    print("3. AI & Machine Learning Focus")
    print("4. Startup Technology Report")
    print("5. Custom Combined Query")

    try:
        choice = input("\nEnter your choice (1-5): ").strip()

        if choice == "1":
            print("\n🚀 Generating comprehensive tech report...")
            filepath = hub.generate_comprehensive_tech_report()
            print(f"✅ Report completed: {filepath}")

        elif choice == "2":
            languages = [
                "python",
                "javascript",
                "typescript",
                "java",
                "go",
                "rust",
                "cpp",
                "csharp",
                "php",
                "ruby",
                "swift",
                "kotlin",
            ]

            print("\nPopular languages:")
            for i, lang in enumerate(languages, 1):
                print(f"  {i:2d}. {lang.title()}")

            lang_choice = input("\nEnter number or language name: ").strip()
            language = None

            if lang_choice.isdigit() and 1 <= int(lang_choice) <= len(languages):
                language = languages[int(lang_choice) - 1]
            elif lang_choice.lower() in languages or lang_choice:
                language = lang_choice.lower()

            if language:
                print(f"\n🚀 Generating {language} ecosystem report...")
                filepath = hub.generate_language_ecosystem_report(language)
                print(f"✅ Report completed: {filepath}")
            else:
                print("❌ Invalid language selection")

        elif choice == "3":
            print("\n🤖 Generating AI & ML report...")
            filepath = hub.generate_ai_focus_report()
            print(f"✅ Report completed: {filepath}")

        elif choice == "4":
            print("\n💼 Generating startup technology report...")
            filepath = hub.generate_startup_tech_report()
            print(f"✅ Report completed: {filepath}")

        elif choice == "5":
            news_query = input("Enter news query: ").strip()
            github_query = input("Enter GitHub trending query: ").strip()

            if news_query and github_query:
                print("\n🔍 Generating custom combined report...")

                news_agent = create_enhanced_news_agent()
                github_agent = create_github_trending_agent()

                news_response = news_agent.run(news_query)
                github_response = github_agent.run(github_query)

                combined_content = f"""# Custom Tech Report

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
**News Query:** {news_query}
**GitHub Query:** {github_query}

---

## 📰 News Results

{news_response.content}

---

## 🚀 GitHub Trending Results

{github_response.content}

---
*Generated by Agno Tech News Hub*
"""

                timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
                filepath = hub.reports_dir / f"custom_tech_report_{timestamp}.md"

                with open(filepath, "w", encoding="utf-8") as f:
                    f.write(combined_content)

                print(f"✅ Custom report completed: {filepath}")
            else:
                print("❌ Both queries are required")

        else:
            print("❌ Invalid choice")

        print(f"\n📁 Check the '{hub.reports_dir}' folder for your report!")

    except KeyboardInterrupt:
        print("\n👋 Report generation cancelled")
    except Exception as e:
        print(f"❌ Error: {e}")


if __name__ == "__main__":
    main()
