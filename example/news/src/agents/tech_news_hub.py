#!/usr/bin/env python3
"""
Tech News Hub - Combined GitHub Trending + General Tech News
Integrates GitHub trending repositories with general tech news
"""

from datetime import datetime
import os
from pathlib import Path
import sys

# Add current directory to path for imports
current_dir = Path(__file__).parent
sys.path.insert(0, str(current_dir))

from dotenv import load_dotenv
from github_trending_agent import create_github_trending_agent
from multisource_news_agent import create_enhanced_news_agent

# Load environment variables
load_dotenv()


class TechNewsHub:
    """Comprehensive tech news hub combining multiple sources"""

    def __init__(self, reports_dir="reports"):
        self.reports_dir = Path(reports_dir)
        self.reports_dir.mkdir(exist_ok=True)

    def generate_comprehensive_tech_report(self, filename=None):
        """Generate a comprehensive tech report combining news and GitHub trends"""
        # Create both agents
        news_agent = create_enhanced_news_agent()
        github_agent = create_github_trending_agent()

        print("🔍 Gathering tech news...")
        news_response = news_agent.run(
            "What are the latest technology news, AI developments, and startup announcements today?"
        )

        print("🔍 Gathering GitHub trending repositories...")
        github_response = github_agent.run(
            "What are the trending GitHub repositories today across all languages, with focus on AI, web development, and developer tools?"
        )

        # Combine responses
        combined_content = f"""# Comprehensive Tech News Report

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

---

## 📰 Latest Tech News & Developments

{news_response.content}

---

## 🚀 Trending GitHub Repositories

{github_response.content}

---

## 🔗 Cross-References & Connections

*This section would benefit from AI analysis to find connections between news stories and trending repositories*

---
*Generated by Agno Multi-Source Tech News Hub*
"""

        # Save combined report
        if not filename:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            filename = f"comprehensive_tech_report_{timestamp}"

        filepath = self.reports_dir / f"{filename}.md"
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(combined_content)

        print(f"📄 Comprehensive report saved to: {filepath}")
        return filepath

    def generate_language_ecosystem_report(self, language, filename=None):
        """Generate a report on a specific programming language ecosystem"""
        news_agent = create_enhanced_news_agent()
        github_agent = create_github_trending_agent(language=language)

        print(f"🔍 Gathering {language} news...")
        news_query = f"Find the latest news, updates, and developments related to {language} programming language, frameworks, libraries, and ecosystem"
        news_response = news_agent.run(news_query)

        print(f"🔍 Gathering trending {language} repositories...")
        github_query = f"Show me trending {language} repositories with detailed analysis of what makes them popular and newsworthy"
        github_response = github_agent.run(github_query)

        # Combine responses
        combined_content = f"""# {language.title()} Ecosystem Report

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
**Language:** {language.title()}

---

## 📰 {language.title()} News & Updates

{news_response.content}

---

## 🚀 Trending {language.title()} Repositories

{github_response.content}

---

## 📊 Ecosystem Insights

*This {language} ecosystem report combines news coverage with repository trends to provide a comprehensive view of current developments.*

---
*Generated by Agno Tech News Hub*
"""

        # Save report
        if not filename:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            filename = f"{language}_ecosystem_report_{timestamp}"

        filepath = self.reports_dir / f"{filename}.md"
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(combined_content)

        print(f"📄 {language.title()} ecosystem report saved to: {filepath}")
        return filepath

